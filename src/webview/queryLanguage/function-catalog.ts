/**
 * Дерево «Функции языка запросов» — тот же состав и порядок, что в конструкторе
 * запросов 1С. Вставляется шаблон в синтаксисе сниппетов Monaco: ${1:Строка} —
 * поле, которое выделяется после вставки, Tab переходит к следующему.
 */

export type CatalogItem = {
  label: string;
  snippet: string;
};

export type CatalogFolder = {
  label: string;
  children: (CatalogFolder | CatalogItem)[];
};

export const isCatalogFolder = (node: CatalogFolder | CatalogItem): node is CatalogFolder =>
  "children" in node;

/** Функция с параметрами: ПОДСТРОКА(${1:Строка}, ${2:Начало}, ${3:Длина}). */
const fn = (name: string, ...parameters: string[]): CatalogItem => ({
  label: name,
  snippet: `${name}(${parameters.map((parameter, i) => `\${${i + 1}:${parameter}}`).join(", ")})`,
});

/** Оператор вставляется как есть. */
const op = (label: string, snippet = label): CatalogItem => ({ label, snippet });

