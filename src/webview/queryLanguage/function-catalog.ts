/**
 * Шаблон как обычный текст: с именами полей — для подсказки,
 * ПОДСТРОКА(Строка, Начало, Длина), без них — для перетаскивания, ПОДСТРОКА(, , ).
 */
export function snippetText(snippet: string, withPlaceholders: boolean): string {
  return snippet.replace(/\$\{\d+:([^}]*)\}/g, withPlaceholders ? "$1" : "").replace(/\$\d+/g, "");
}
